// 도화 부재 시 SAL_PRIORITY 우선순위로 카피 결정.
// charm_sals.py SAL_PRIORITY와 동기화: 천을귀인 > 홍염 > 금여 > 화개 > 공망.
export function pickDohwaCopyKey(
  dohwa: CharmDohwaView,
  variantTags: CharmVariantTag[]
): DohwaCopyKey {
  if (!dohwa.present) {
    if (variantTags.includes("cheoneul_present")) return "absent_cheoneul";
    if (variantTags.includes("hongyeom_present")) return "absent_hongyeom";
    if (variantTags.includes("geumyeo_present")) return "absent_geumyeo";
    if (variantTags.includes("hwagae_present")) return "absent_hwagae";
    if (variantTags.includes("gongmang_present")) return "absent_gongmang";
    return "absent";
  }
  if (variantTags.includes("dohwa_multi")) return "multi";
  return (dohwa.pillar ?? "day") as DohwaCopyKey;
}
